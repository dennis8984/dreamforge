const DICTS: Record<Lang, typeof en> = { en, es, fr, de, pt };

const I18nContext = createContext<{
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: MessageKey) => string;
}>({
  lang: 'en',
  setLang: () => {},
  t: (key) => en[key],
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');

  useEffect(() => {
    const saved = window.localStorage.getItem('df-lang');
    if (saved && saved in DICTS) setLangState(saved as Lang);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo(() => {
    const dict = DICTS[lang];
    return {
      lang,
      setLang: (next: Lang) => {
        setLangState(next);
        window.localStorage.setItem('df-lang', next);
      },
      t: (key: MessageKey) => dict[key] || en[key],
    };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

export function LanguageMenu() {
  const { lang, setLang, t } = useI18n();
  const [open, setOpen] = useState(false);
  const current = LANGS.find((item) => item.id === lang) || LANGS[0];

  return (
    <div className="relative">
      <button
        type="button"
        aria-label={t('lang.label')}
        onClick={() => setOpen((value) => !value)}
        className="h-[34px] min-w-[42px] rounded-full border border-white/20 px-2 text-[12px] font-semibold text-white"
      >
        {current.short}
      </button>
      {open ? (
        <div className="absolute right-0 top-10 z-50 w-40 rounded-xl border border-white/10 bg-[#1c1c1f] p-1 shadow-xl">
          {LANGS.map((item) => (
            <button
              key={item.id}
              type="button"
              onClick={() => {
                setLang(item.id);
                setOpen(false);
              }}
              className={`block w-full rounded-lg px-3 py-2 text-left text-[13px] ${
                item.id === lang ? 'bg-[#303030] text-white' : 'text-[#d1d1d1]'
              }`}
            >
              {item.label}
            </button>
          ))}
        </div>
      ) : null}
    </div>
  );
}
